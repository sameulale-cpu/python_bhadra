# For loop:
# loop depends on the number of data existing in the iterable

# iterable: sequential data(group datatype, string)
# iteration: process of moving from first index to last index of the sequence
# iterator: variable used to perform iteration in iterable

# Syntax :
# 1 in a
# for iterator in iterable:
#    statement1
#    statement2

a = [1, 2, 3, 4, 5]
for i in a:  # i = 1(first loop(iteration)), 2 (second iteration), 3,4,5
    print("Hello", i)
