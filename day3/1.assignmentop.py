# Assignment operator: symbols used to data to a variable

# 1. equal to(=)
a = 10
print(a)

# 2. add and assign(+=)
a += 5  # a = a + 5
print(a) # 10 + 5 = 15

# 3. subtract and assign(-=)
a -= 2  # a = a -2
print(a) # 15-2 = 13

# 4. multiply and assign (*=)
a *= 2 # a = a * 2
print(a) # 13 * 2 = 26

# 5. divide and assign (/=)
a /= 2 # 26 / 2 = 13
print(a)

# 6. floor and assign (//=)
a //= 2 # 13 //2 = 6 (from 6.5)
print(a)

# 7. modular and assign (%=)
a %= 5 # 6 % 5 = 1
print(a)

# 8. exponential and assign (**=)
a **= 2 # 1^ =2 = 1
print(a)