# comparison operator : used to compare the value, Output: boolean

a = 10
b = 5
# ==: If equal then output : True , otherwise False
print(a == b)

# not equal(!=) : if values are equal false
print(a != 5)

# > : if a greater than b then true
print(a > b)

# < : if a smaller than b then true
print(a < b)

# greater than or equal to(>=) : if a greater or equal to b then true
print(a >= b)

# (<=) : if a less or equal to b then true
print(a <= b)
